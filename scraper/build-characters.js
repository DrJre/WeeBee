// WeeBee Character Database Builder
// Run once: node scraper/build-characters.js
// Output: characters.js in project root

import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const OUTPUT = path.join(__dirname, '..', 'characters.js');
const ANILIST = 'https://graphql.anilist.co';

const sleep = ms => new Promise(r => setTimeout(r, ms));

async function gql(query, variables = {}) {
    const res = await fetch(ANILIST, {
        method: 'POST',
        headers: { 'Content-Type': 'application/json', 'Accept': 'application/json' },
        body: JSON.stringify({ query, variables })
    });
    if (res.status === 429) {
        console.log('  Rate limited, waiting 60s...');
        await sleep(60000);
        return gql(query, variables);
    }
    const json = await res.json();
    if (json.errors) throw new Error(json.errors[0].message);
    return json.data;
}

// Fetch top N popular anime from AniList (TV series + movies, exclude hentai)
async function getTopAnime(count = 50) {
    const perPage = 50;
    const pages = Math.ceil(count / perPage);
    const results = [];

    for (let page = 1; page <= pages; page++) {
        const data = await gql(`
            query ($page: Int, $perPage: Int) {
                Page(page: $page, perPage: $perPage) {
                    media(
                        sort: POPULARITY_DESC
                        type: ANIME
                        format_in: [TV, MOVIE, TV_SHORT]
                        isAdult: false
                    ) {
                        id
                        idMal
                        title { english romaji }
                    }
                }
            }
        `, { page, perPage });

        results.push(...data.Page.media);
        if (page < pages) await sleep(800);
    }

    return results.slice(0, count);
}

// Fetch top 20 characters for an AniList media ID
async function getCharacters(anilistId, animeName) {
    const data = await gql(`
        query ($id: Int) {
            Media(id: $id, type: ANIME) {
                characters(sort: FAVOURITES_DESC, perPage: 20) {
                    nodes {
                        name { full }
                        image { large }
                        favourites
                    }
                }
            }
        }
    `, { id: anilistId });

    const nodes = data?.Media?.characters?.nodes || [];
    return nodes
        .filter(c => c.name?.full && c.image?.large)
        .map(c => ({
            name: c.name.full,
            image: c.image.large,
            anime: animeName
        }));
}

async function main() {
    console.log('Fetching top 50 anime from AniList...');
    const anime = await getTopAnime(50);
    console.log(`Got ${anime.length} anime.\n`);

    const allCharacters = [];
    const seenNames = new Set();

    for (let i = 0; i < anime.length; i++) {
        const a = anime[i];
        const title = a.title.english || a.title.romaji;
        process.stdout.write(`[${i + 1}/50] ${title}... `);

        try {
            const chars = await getCharacters(a.id, title);
            let added = 0;
            for (const c of chars) {
                // Skip exact name dupes (same character in multiple seasons)
                if (!seenNames.has(c.name.toLowerCase())) {
                    seenNames.add(c.name.toLowerCase());
                    allCharacters.push(c);
                    added++;
                }
            }
            console.log(`${added} characters`);
        } catch (e) {
            console.log(`ERROR: ${e.message}`);
        }

        // Respect AniList rate limit (~90 req/min = ~670ms between requests)
        if (i < anime.length - 1) await sleep(750);
    }

    console.log(`\nTotal unique characters: ${allCharacters.length}`);

    const output = `// WeeBee Character Database — auto-generated by scraper/build-characters.js
// ${allCharacters.length} characters from top 50 anime | Last updated: ${new Date().toISOString().split('T')[0]}
// DO NOT EDIT MANUALLY — re-run the scraper to update

window.WB_CHARACTERS = ${JSON.stringify(allCharacters, null, 2)};
`;

    fs.writeFileSync(OUTPUT, output, 'utf8');
    console.log(`\nWrote ${OUTPUT}`);
    console.log(`File size: ${(fs.statSync(OUTPUT).size / 1024).toFixed(1)} KB`);
}

main().catch(e => {
    console.error('Fatal:', e);
    process.exit(1);
});
